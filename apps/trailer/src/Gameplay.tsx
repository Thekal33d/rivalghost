import {useLayoutEffect,useRef} from 'react';
import {createExpedition,houndInput,type ExpeditionSnapshot} from '@rivalghost/sim';
import {CHAPTERS,type ChapterId,type TrailId} from '@rivalghost/game-data';
import {drawExpedition} from '../../web/src/expedition-art';
import {flightView} from '../../web/src/flight-view';
const cache=new Map<number,{game:ReturnType<typeof createExpedition>;frames:ExpeditionSnapshot[]}>();
export function snapshot(chapter:number,tick:number){
 let entry=cache.get(chapter);if(!entry){const game=createExpedition({chapter:chapter as ChapterId,rig:'fan',seed:CHAPTERS[chapter].seed,rulesVersion:3});entry={game,frames:[game.snapshot()]};cache.set(chapter,entry);}
 tick=Math.max(0,Math.floor(tick));
 while(entry.frames.length<=tick&&!entry.game.snapshot().finished){entry.game.step(houndInput(entry.game.snapshot(),'ace'));entry.frames.push(entry.game.snapshot());}
 return {state:entry.frames[Math.min(tick,entry.frames.length-1)],events:entry.game.events};
}
/** Unchanged game engine and art. Inputs are generated by the existing NPC replay controller. */
export function Gameplay({chapter=2,tick,trail,restoration=0,opacity=1}:{chapter?:number;tick:number;trail?:TrailId;restoration?:number;opacity?:number}){
 const ref=useRef<HTMLCanvasElement>(null);
 useLayoutEffect(()=>{const ctx=ref.current?.getContext('2d');if(!ctx)return;const {state,events}=snapshot(chapter,tick);ctx.clearRect(0,0,1920,1080);drawExpedition(ctx,state,events,false,undefined,flightView(1920,1080),'RIVAL',trail,restoration);},[chapter,tick,trail,restoration]);
 return <canvas ref={ref} width={1920} height={1080} style={{position:'absolute',inset:0,width:'100%',height:'100%',opacity}}/>;
}
